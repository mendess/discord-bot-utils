#[derive(Debug, Default, Clone, Copy)]
pub struct HandlerOptions {
    pub include_bot_generated_events: bool,
}

#[derive(Clone)]
pub struct Handler<'s, S: TypeMapKey> {
    bot_id: OnceLock<UserId>,
    bus: &'s EventBus<S>,
    options: HandlerOptions,
}

impl<'s, S: TypeMapKey> Handler<'s, S> {
    /// The bot_id, if passed, will serve to filter a few events that are generated by bot actions
    /// such as new messages and reactions.
    pub fn new(bus: &'s EventBus<S>, options: HandlerOptions) -> Self {
        Self {
            bot_id: OnceLock::new(),
            bus,
            options,
        }
    }
}

pub struct Context<S: TypeMapKey> {
    pub serenity: serenity::client::Context,
    pub state: S::Value,
}

async fn state<S>(ctx: &serenity::client::Context) -> S::Value
where
    S: TypeMapKey,
    S::Value: Default + Clone,
{
    ctx.data
        .write()
        .await
        .get::<S>()
        .cloned()
        .unwrap_or_default()
}

